/**
 * Design system sync (stage 1 of the UniRead design-system process, docs/14 §15): pull UniRead's variables, styles and
 * component inventory into the repo, pinned to one design-system version.
 *
 *   npx tsx scripts/ds-sync.ts --snapshot docs/uniread-spec/design-system/UniRead-设计规范.html [--label DS-2026-11-03]
 *       from the design-system snapshot issued by UniRead (the HTML's embedded design-data)
 *   FIGMA_TOKEN=… npx tsx scripts/ds-sync.ts --figma [--label …]
 *       from Figma: Variables REST API (Enterprise, file_variables:read) + file styles / component sets
 *
 * Writes (never by hand):
 *   design-system/tokens/uniread.tokens.json   DTCG tokens: variables, paint / text / effect / grid styles
 *   design-system/components.inventory.json     every component / component set with its variant properties and node ids
 *   design-system/lock.json                     the pinned version: source, label, Figma version, date, sha256 of each output
 * Then run `npx tsx scripts/ds-build.ts` (CSS) and, when a previous lock existed, `npx tsx scripts/ds-diff.ts`.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';

export const FILE_KEY = 'gYPHIUtQ50mXuoE0Cfpmu0';
const OUT = 'design-system';
const sha = (s: string | Buffer) => createHash('sha256').update(s).digest('hex');

type SnapVar = { name: string; group: string; collection: string; mode: string; type: 'COLOR' | 'FLOAT' | 'STRING'; value: unknown; alpha?: number; css: string; unit?: string; alias?: string };
type Snapshot = {
  meta: { date: string; sourceUrl: string; collection: string; mode: string };
  variables: SnapVar[];
  textStyles: { name: string; fontAlias?: string; family: string; fontStyle: string; weight: number; size: number; lineHeight: number; letterSpacing: string; description?: string }[];
  paintStyles: { name: string; occurrence: number; duplicates: number; type: string; hex?: string; alpha?: number; css?: string; stops?: { position: number; hex: string; alpha: number }[]; documentedAssetId?: string }[];
  effectStyles: { name: string; css: string; layers: unknown[]; documentedAssetId?: string }[];
  gridStyles: Record<string, unknown>[];
  dependencies: { name: string; type: string; value: unknown; alpha?: number }[];
  designSystem: {
    sourceUrl: string;
    components: { name: string; group: string; kind: 'set' | string; variantCount: number; properties: string; nodeId: string; sourceUrl: string }[];
  };
  componentPreviews: Record<string, { variants: { id: string; name: string; props: Record<string, string> | string }[] }>;
};

/** DTCG token tree from "a/b/c" names; same-name assets keep their occurrence (Figma allows duplicates) */
function put(tree: Record<string, unknown>, path: string[], token: Record<string, unknown>) {
  let node = tree;
  for (const p of path.slice(0, -1)) node = (node[p] ??= {}) as Record<string, unknown>;
  node[path.at(-1)!] = token;
}
const pathOf = (name: string) => name.split('/').map((s) => s.trim());

export function fromSnapshot(html: string) {
  const m = /<script id="design-data" type="application\/json">([\s\S]*?)<\/script>/.exec(html);
  if (!m) throw new Error('no design-data in the snapshot');
  const d = JSON.parse(m[1]) as Snapshot;
  const tokens: Record<string, unknown> = {
    $description: `UniRead design system — ${d.meta.collection} / ${d.meta.mode}; generated by scripts/ds-sync.ts, do not edit`,
  };
  const variables: Record<string, unknown> = {};
  for (const v of d.variables) {
    put(variables, pathOf(v.name), {
      $type: v.type === 'COLOR' ? 'color' : v.type === 'FLOAT' ? 'dimension' : 'string',
      $value: v.type === 'COLOR' ? v.css : v.type === 'FLOAT' ? (v.unit ? `${v.value}${v.unit}` : v.value) : v.value,
      $extensions: { figma: { collection: v.collection, mode: v.mode, type: v.type, ...(v.alias ? { alias: v.alias, alpha: v.alpha } : {}) } },
    });
  }
  tokens.variables = variables;
  const paint: Record<string, unknown> = {};
  for (const p of d.paintStyles) {
    const path = pathOf(p.name);
    if (p.duplicates > 1) path[path.length - 1] += ` #${p.occurrence}`;
    const value = p.type === 'SOLID' ? p.css : p.type.startsWith('GRADIENT') ? { stops: p.stops } : null;
    put(paint, path, { $type: p.type === 'SOLID' ? 'color' : p.type.startsWith('GRADIENT') ? 'gradient' : 'empty', $value: value, $extensions: { figma: { styleType: p.type, assetId: p.documentedAssetId?.replace(/,$/, '') } } });
  }
  tokens.paint = paint;
  const text: Record<string, unknown> = {};
  for (const t of d.textStyles) {
    put(text, pathOf(t.name), {
      $type: 'typography',
      $value: { fontFamily: t.family, fontWeight: t.weight, fontSize: `${t.size}px`, lineHeight: `${t.lineHeight}px`, letterSpacing: t.letterSpacing },
      $extensions: { figma: { fontStyle: t.fontStyle, fontAlias: t.fontAlias } },
    });
  }
  tokens.text = text;
  const effect: Record<string, unknown> = {};
  for (const e of d.effectStyles) put(effect, pathOf(e.name), { $type: 'shadow', $value: e.css, $extensions: { figma: { layers: e.layers, assetId: e.documentedAssetId?.replace(/,$/, '') } } });
  tokens.effect = effect;
  tokens.grid = Object.fromEntries(d.gridStyles.map((g) => [g.name as string, { $type: 'grid', $value: Object.fromEntries(Object.entries(g).filter(([k]) => !['name', 'cssName'].includes(k))) }]));
  tokens.externalDependencies = d.dependencies;

  const components = d.designSystem.components.map((c) => ({
    name: c.name,
    group: c.group,
    kind: c.kind === 'set' ? 'COMPONENT_SET' : 'COMPONENT',
    nodeId: c.nodeId,
    variantCount: c.variantCount,
    properties: c.properties,
    variants: (d.componentPreviews[c.nodeId]?.variants ?? []).map((v) => ({ nodeId: v.id, name: v.name })),
  }));
  return { tokens, components, version: { source: 'snapshot', date: d.meta.date, sourceUrl: d.designSystem.sourceUrl } };
}

async function fromFigma(token: string) {
  const get = async (path: string) => {
    const r = await fetch(`https://api.figma.com/v1/${path}`, { headers: { 'X-Figma-Token': token } });
    if (!r.ok) throw new Error(`GET ${path}: HTTP ${r.status} ${await r.text()}`);
    return r.json() as Promise<any>;
  };
  // the version this sync pins: the latest saved version of the file
  const versions = await get(`files/${FILE_KEY}/versions`);
  const head = versions.versions[0];
  const vars = await get(`files/${FILE_KEY}/variables/local`);
  const sets = await get(`files/${FILE_KEY}/component_sets`);
  const comps = await get(`files/${FILE_KEY}/components`);
  const styles = await get(`files/${FILE_KEY}/styles`);
  // Raw REST payloads are normalised to the same shapes as the snapshot path where they overlap; style values need
  // node reads (files/:key/nodes) and are fetched by ds-sync in a later step when this path is first exercised.
  return {
    tokens: { $description: 'UniRead design system from the Figma REST API (raw variables; see ds-sync)', variablesRaw: vars.meta, stylesRaw: styles.meta.styles },
    components: [
      ...sets.meta.component_sets.map((c: any) => ({ name: c.name, kind: 'COMPONENT_SET', nodeId: c.node_id, key: c.key, page: c.containing_frame?.pageName, frame: c.containing_frame?.name })),
      ...comps.meta.components.filter((c: any) => !c.containing_frame?.containingComponentSet).map((c: any) => ({ name: c.name, kind: 'COMPONENT', nodeId: c.node_id, key: c.key, page: c.containing_frame?.pageName })),
    ],
    version: { source: 'figma', figmaVersionId: head.id, figmaVersionLabel: head.label, date: head.created_at.slice(0, 10) },
  };
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const args = process.argv.slice(2);
  const opt = (n: string) => (args.includes(`--${n}`) ? args[args.indexOf(`--${n}`) + 1] : undefined);
  const snapshotPath = opt('snapshot');
  let result;
  let sourceSha: string | undefined;
  if (snapshotPath) {
    const html = readFileSync(snapshotPath);
    sourceSha = sha(html);
    result = fromSnapshot(html.toString('utf8'));
  } else if (args.includes('--figma')) {
    if (!process.env.FIGMA_TOKEN) throw new Error('FIGMA_TOKEN is not set');
    result = await fromFigma(process.env.FIGMA_TOKEN);
  } else {
    console.error('usage: npx tsx scripts/ds-sync.ts --snapshot <UniRead-设计规范.html> | --figma   [--label <DS version label>]');
    process.exit(1);
  }
  mkdirSync(`${OUT}/tokens`, { recursive: true });
  const tokensText = JSON.stringify(result.tokens, null, 2) + '\n';
  const compText = JSON.stringify(result.components, null, 1) + '\n';
  writeFileSync(`${OUT}/tokens/uniread.tokens.json`, tokensText);
  writeFileSync(`${OUT}/components.inventory.json`, compText);
  const prev = existsSync(`${OUT}/lock.json`) ? JSON.parse(readFileSync(`${OUT}/lock.json`, 'utf8')) : null;
  const lock = {
    designSystem: 'UniRead',
    figmaFileKey: FILE_KEY,
    label: opt('label') ?? `DS-${result.version.date}`,
    ...result.version,
    ...(snapshotPath ? { snapshot: snapshotPath, snapshotSha256: sourceSha } : {}),
    syncedAt: new Date().toISOString().slice(0, 10),
    outputs: { 'tokens/uniread.tokens.json': sha(tokensText), 'components.inventory.json': sha(compText) },
    previous: prev ? { label: prev.label, date: prev.date } : null,
  };
  writeFileSync(`${OUT}/lock.json`, JSON.stringify(lock, null, 2) + '\n');
  console.log(`${lock.label}: ${result.components.length} components → ${OUT}/ (previous: ${prev?.label ?? 'none'})`);
}
